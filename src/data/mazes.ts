export const classicMaze = () => {
  const m = Maze.parse(CLASSIC, 'Classic');
  // Arcade "no upward turn" tiles above the ghost house and above the start.
  for (const [x, y] of [[12, 11], [15, 11], [12, 23], [15, 23]]) m.noUp.add(y * m.w + x);
  return m;
};
